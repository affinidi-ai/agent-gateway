import React, { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import {
  AgentCardResponse,
  AgentCardSource,
  AgentSurfaceRef,
  ApiError,
  apiClient,
} from '../../api';
import { AppButton } from '../../components/shared/AppButton';
import FormSelect from '../../components/shared/FormSelect';
import { tokenizeJson } from '../../components/shared/jsonHighlight';
import { SurfaceLinkButton } from '../IdentitiesPage/IdentitySurfaceCell';
import AgentCardPreview from './AgentCardPreview';

type CardView = 'preview' | 'json';

const CARD_VIEWS: { key: CardView; label: string; icon: string }[] = [
  { key: 'preview', label: 'Preview', icon: 'fa-eye' },
  { key: 'json', label: 'JSON', icon: 'fa-code' },
];

type UnavailableReason = Extract<AgentCardResponse, { available: false }>['reason'];

const UNAVAILABLE_TEXT: Record<UnavailableReason, string> = {
  no_agent_card: "This agent doesn't publish an Agent Card",
  not_running: "None of this agent's surfaces is running on this gateway",
  operator_only:
    'Only an appliance operator can read the Agent Card of an agent behind appliance-wide surfaces',
};

const CARD_SOURCE_TEXT: Record<AgentCardSource, string> = {
  fetched: 'Fetched & rewritten by the gateway',
  generated: 'Generated by the A2A proxy',
  remote_gateway: 'Relayed from the remote gateway',
};

interface SurfacePickerProps {
  ids: string[];
  value: string;
  names: Map<string, string>;
  onChange: (surfaceId: string) => void;
}

/**
 * The surface the card is read through: a link to it, or a select with an Open surface link when
 * there are several.
 */
const SurfacePicker: React.FC<SurfacePickerProps> = ({ ids, value, names, onChange }) => {
  const navigate = useNavigate();
  const openSurface = (surfaceId: string) => navigate(`/surfaces/${surfaceId}`);
  const options = useMemo(
    () => ids.map(id => ({ value: id, label: names.get(id) ?? id })),
    [ids, names]
  );
  if (ids.length < 2) {
    return (
      <SurfaceLinkButton
        surface={{ id: value, name: names.get(value) ?? value, deleted: false }}
        onOpen={openSurface}
        data-testid="agent-card-surface"
      />
    );
  }
  return (
    <>
      <FormSelect
        value={value}
        options={options}
        onChange={onChange}
        ariaLabel="Surface serving the Agent Card"
        className="d-inline-block"
        testid="agent-card-surface-select"
      />
      <button
        type="button"
        className="btn btn-link btn-sm p-0 ms-1"
        onClick={() => openSurface(value)}
        data-testid="agent-card-open-surface-button"
      >
        Open surface
      </button>
    </>
  );
};

/**
 * Copy, styled like the Verifiable Presentation viewer's (`VpViewer`): an `outline-secondary`
 * `AppButton` that reads "Copied" with a check for two seconds.
 */
const CopyJsonButton: React.FC<{ text: string }> = ({ text }) => {
  const [copied, setCopied] = useState(false);
  const timer = useRef<ReturnType<typeof setTimeout>>();
  useEffect(() => () => clearTimeout(timer.current), []);
  const handleCopy = () => {
    void navigator.clipboard?.writeText(text);
    setCopied(true);
    clearTimeout(timer.current);
    timer.current = setTimeout(() => setCopied(false), 2000);
  };
  return (
    <AppButton
      variant="outline-secondary"
      size="sm"
      onClick={handleCopy}
      title="Copy JSON to clipboard"
      aria-label="Copy JSON"
      iconStart={
        <i
          className={`fas ${copied ? 'fa-check text-success' : 'fa-copy'} me-1`}
          aria-hidden="true"
        />
      }
      data-testid="agent-card-copy-button"
    >
      {copied ? 'Copied' : 'Copy'}
    </AppButton>
  );
};

/** The card as highlighted, plain-text JSON. */
const CardJson: React.FC<{ json: string }> = ({ json }) => {
  const tokens = useMemo(() => tokenizeJson(json), [json]);
  return (
    <pre className="vp-json-pre agent-card-json" data-testid="agent-card-json">
      <code>
        {tokens.map((token, i) =>
          token.type === 'plain' ? (
            <React.Fragment key={i}>{token.value}</React.Fragment>
          ) : (
            <span key={i} className={`json-${token.type}`}>
              {token.value}
            </span>
          )
        )}
      </code>
    </pre>
  );
};

interface AgentCardTabProps {
  agentId: string;
  /** The agent's surfaces, to name the one serving the card. */
  surfaces: AgentSurfaceRef[];
}

/**
 * The card the gateway serves for the agent, as callers get it, read through one surface.
 * It is untrusted, agent-supplied content: shown only as plain text, never as HTML or links.
 */
const AgentCardTab: React.FC<AgentCardTabProps> = ({ agentId, surfaces }) => {
  const [response, setResponse] = useState<AgentCardResponse | null>(null);
  const [loading, setLoading] = useState(true);
  const [failed, setFailed] = useState(false);
  const [surfaceUnavailable, setSurfaceUnavailable] = useState(false);
  const [view, setView] = useState<CardView>('preview');
  const [surfaceId, setSurfaceId] = useState<string | undefined>(undefined);
  const latest = useRef(0);
  const names = useMemo(
    () => new Map(surfaces.map(surface => [surface.surface_id, surface.name])),
    [surfaces]
  );

  const loadCard = useCallback(async () => {
    const request = ++latest.current;
    try {
      setLoading(true);
      setFailed(false);
      setSurfaceUnavailable(false);
      const card = await apiClient.getAgentCard(agentId, surfaceId);
      if (request === latest.current) setResponse(card);
    } catch (err) {
      if (request !== latest.current) return;
      if (surfaceId && err instanceof ApiError && err.code === 'surface_unavailable') {
        setSurfaceUnavailable(true);
      }
      else setFailed(true);
    } finally {
      if (request === latest.current) setLoading(false);
    }
  }, [agentId, surfaceId]);

  useEffect(() => {
    loadCard();
  }, [loadCard]);

  if (loading) {
    return (
      <div className="text-center py-4" data-testid="agent-card-loading">
        <div className="spinner-border spinner-border-sm text-primary" role="status">
          <span className="visually-hidden">Loading Agent Card</span>
        </div>
      </div>
    );
  }

  if (failed || !response) {
    return (
      <div className="alert alert-danger d-flex align-items-center" data-testid="agent-card-error">
        <i className="fas fa-exclamation-circle me-2" aria-hidden="true" />
        Agent Card couldn&apos;t be loaded
        <AppButton
          variant="outline-danger"
          size="sm"
          className="ms-3"
          onClick={loadCard}
          data-testid="agent-card-retry-button"
        >
          Retry
        </AppButton>
      </div>
    );
  }

  const cardSurfaceIds = response.card_surface_ids ?? [];

  if (surfaceUnavailable && surfaceId) {
    return (
      <>
        <div className="d-flex align-items-center gap-2 mb-2">
          <span className="text-muted">Served by</span>
          <SurfacePicker
            ids={cardSurfaceIds}
            value={surfaceId}
            names={names}
            onChange={setSurfaceId}
          />
        </div>
        <div className="text-muted py-4 text-center" data-testid="agent-card-surface-unavailable">
          <i className="fas fa-id-card fa-2x mb-2 d-block" aria-hidden="true" />
          The Agent Card can&apos;t be read through this surface on this gateway
          <div className="mt-2">
            <AppButton
              variant="outline-secondary"
              size="sm"
              onClick={loadCard}
              data-testid="agent-card-surface-retry-button"
            >
              Retry
            </AppButton>
          </div>
        </div>
      </>
    );
  }

  if (!response.available) {
    return (
      <div className="text-muted py-4 text-center" data-testid={`agent-card-${response.reason}`}>
        <i className="fas fa-id-card fa-2x mb-2 d-block" aria-hidden="true" />
        {UNAVAILABLE_TEXT[response.reason] ?? "Agent Card isn't available"}
      </div>
    );
  }

  const json = JSON.stringify(response.card, null, 2);
  const sourceText = CARD_SOURCE_TEXT[response.source];
  const servedBy = response.surface_id;
  return (
    <div className="card" data-testid="agent-card-tab">
      <div className="card-header py-2 d-flex flex-wrap gap-2 align-items-center justify-content-between">
        {servedBy || sourceText ? (
          <div
            className="d-flex flex-wrap align-items-center gap-1"
            data-testid="agent-card-source"
            data-source={sourceText ? response.source : undefined}
          >
            {servedBy && (
              <>
                <span className="text-muted me-1">Served by</span>
                <SurfacePicker
                  ids={cardSurfaceIds.length ? cardSurfaceIds : [servedBy]}
                  value={servedBy}
                  names={names}
                  onChange={setSurfaceId}
                />
              </>
            )}
            {servedBy && sourceText && (
              <span className="text-muted mx-1" aria-hidden="true">
                ·
              </span>
            )}
            {sourceText && <span data-testid="agent-card-source-text">{sourceText}</span>}
          </div>
        ) : (
          <span />
        )}
        <div className="d-flex align-items-center gap-2" role="group" aria-label="Agent Card view">
          {CARD_VIEWS.map(v => (
            <AppButton
              key={v.key}
              variant={view === v.key ? 'primary' : 'outline-secondary'}
              size="sm"
              aria-pressed={view === v.key}
              onClick={() => setView(v.key)}
              iconStart={<i className={`fas ${v.icon} me-1`} aria-hidden="true" />}
              data-testid={`agent-card-view-${v.key}`}
            >
              {v.label}
            </AppButton>
          ))}
        </div>
      </div>
      {view === 'preview' ? (
        <div className="card-body">
          <AgentCardPreview card={response.card} upstreamCard={response.upstream_card} />
        </div>
      ) : (
        <div className="card-body">
          <div className="d-flex justify-content-end mb-2">
            <CopyJsonButton text={json} />
          </div>
          <CardJson json={json} />
        </div>
      )}
    </div>
  );
};

export default AgentCardTab;
