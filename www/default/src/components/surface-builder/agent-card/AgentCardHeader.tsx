import React from 'react';
import { CopyButton } from '../../shared/CopyButton';
import { AppButton } from '../../shared/AppButton';
import { Badge } from '../../shared/Badge';
import { showToast } from '../../../utils/toaster';
import { describeDeclaration } from '../../../utils/surfaceDeclarations';
import {
  CARD_FETCH_STATUS_LABEL,
  cardNamesGatewayScheme,
  describeCardAuth,
  describeFetchFailure,
  formatLocalTime,
  formatRelativeTime,
  safeHttpUrl,
  type CardFetchStatus,
  type SupportedAgentCardPreview,
} from '../../../utils/agentCardPreview';

export const REFRESH_FORBIDDEN_TITLE = 'You need permission to edit surfaces to refresh the card.';

const STATUS_TONE: Record<CardFetchStatus, 'success' | 'danger' | 'warning'> = {
  ok: 'success',
  failed: 'danger',
  not_served: 'warning',
};

interface AgentCardHeaderProps {
  preview: SupportedAgentCardPreview;
  canEdit: boolean;
  refreshing: boolean;
  onRefresh: () => void;
  now?: number;
}

const AgentCardHeader: React.FC<AgentCardHeaderProps> = ({
  preview,
  canEdit,
  refreshing,
  onRefresh,
  now = Date.now(),
}) => {
  const openUrl = safeHttpUrl(preview.served_url);
  const fetchedAbsolute = formatLocalTime(preview.fetched_at);
  const fetchedRelative = formatRelativeTime(preview.fetched_at, now);
  const outcome = preview.outcome
    ? describeDeclaration(
        preview.outcome,
        undefined,
        preview.after ? cardNamesGatewayScheme(preview.after) : null
      )
    : null;
  const caller = preview.last_caller_fetch;
  const callerRelative = caller ? formatRelativeTime(caller.at, now) : null;
  const callerFailure = caller ? describeFetchFailure(caller) : null;
  const { fetch } = preview;
  const fetchFailure = describeFetchFailure(fetch);

  return (
    <dl className="agent-card-facts" data-testid="agent-card-header">
      <div className="agent-card-fact">
        <dt>Served card discovery URL</dt>
        <dd>
          {preview.served_url ? (
            <code className="agent-card-url" data-testid="agent-card-served-url">
              {preview.served_url}
            </code>
          ) : (
            <span className="text-muted" data-testid="agent-card-served-url">
              No listener serves this surface.
            </span>
          )}
          <span className="agent-card-actions">
            {preview.served_url && (
              <CopyButton
                text={preview.served_url}
                variant="outline-primary"
                label="Copy"
                title="Copy the served card discovery URL"
                aria-label="Copy the served card discovery URL"
                className="ms-0"
                data-testid="agent-card-url-copy-button"
                onCopyError={() => showToast('error', 'Could not copy to the clipboard.')}
              />
            )}
            {openUrl && (
              <a
                className="btn btn-outline-secondary btn-sm"
                href={openUrl}
                target="_blank"
                rel="noopener noreferrer"
                data-testid="agent-card-open-button"
              >
                Open<span className="visually-hidden"> the card in a new tab</span>
                <i className="fas fa-arrow-up-right-from-square ms-1" aria-hidden="true" />
              </a>
            )}
            <AppButton
              variant="outline-primary"
              loading={refreshing}
              loadingLabel="Refreshing"
              disabled={!canEdit}
              title={canEdit ? 'Fetch the card again' : REFRESH_FORBIDDEN_TITLE}
              aria-describedby={canEdit ? undefined : 'agent-card-refresh-hint'}
              onClick={onRefresh}
              data-testid="agent-card-refresh-button"
            >
              Refresh
            </AppButton>
            {!canEdit && (
              <span id="agent-card-refresh-hint" className="visually-hidden">
                {REFRESH_FORBIDDEN_TITLE}
              </span>
            )}
          </span>
        </dd>
      </div>

      <div className="agent-card-fact">
        <dt>Fetched from</dt>
        <dd>
          {preview.source_url ? (
            <>
              <code className="agent-card-url" data-testid="agent-card-source-url">
                {preview.source_url}
              </code>
              {preview.source_url_query_hidden && (
                <span className="text-muted ms-2">(query hidden)</span>
              )}
            </>
          ) : (
            <span className="text-muted" data-testid="agent-card-source-url">
              {preview.generated ? 'Generated by the gateway' : 'No card URL'}
            </span>
          )}
        </dd>
      </div>

      <div className="agent-card-fact">
        <dt>Fetch</dt>
        <dd data-testid="agent-card-fetch">
          <Badge
            value={CARD_FETCH_STATUS_LABEL[fetch.status]}
            tone={STATUS_TONE[fetch.status]}
            data-testid="agent-card-fetch-status"
          />
          {fetch.cause && (
            <span className="ms-2" data-testid="agent-card-fetch-cause" data-cause={fetch.cause}>
              {fetchFailure}
            </span>
          )}
        </dd>
      </div>

      <div className="agent-card-fact">
        <dt>Target Authentication</dt>
        <dd data-testid="agent-card-auth">{describeCardAuth(preview.auth)}</dd>
      </div>

      <div className="agent-card-fact">
        <dt>Last fetched</dt>
        <dd>
          {preview.fetched_at ? (
            <time
              dateTime={preview.fetched_at}
              title={fetchedAbsolute ?? undefined}
              data-testid="agent-card-fetched-at"
            >
              {fetchedRelative ?? fetchedAbsolute ?? preview.fetched_at}
            </time>
          ) : (
            <span className="text-muted" data-testid="agent-card-fetched-at">
              Not fetched
            </span>
          )}
          {preview.cached && <span className="text-muted ms-2">(from the last fetch)</span>}
        </dd>
      </div>

      {outcome && (
        <div className="agent-card-fact">
          <dt>Outcome</dt>
          <dd data-testid="agent-card-outcome">
            <strong>{outcome.label}</strong>
            <span className="text-muted d-block" data-testid="agent-card-outcome-reason">
              {outcome.detail}
            </span>
          </dd>
        </div>
      )}

      {caller && (
        <div className="agent-card-fact">
          <dt>Last caller fetch</dt>
          <dd data-testid="agent-card-last-caller-fetch">
            {CARD_FETCH_STATUS_LABEL[caller.status]}
            {callerFailure && `: ${callerFailure}`}
            {callerRelative && `, ${callerRelative}`}
            <span className="text-muted ms-2">on this gateway</span>
          </dd>
        </div>
      )}
    </dl>
  );
};

export default AgentCardHeader;
