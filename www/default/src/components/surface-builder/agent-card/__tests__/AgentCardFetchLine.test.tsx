import React from 'react';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import '@testing-library/jest-dom';
import AgentCardFetchLine from '../AgentCardFetchLine';
import { SurfaceMetaProvider, type SurfaceMetaValue } from '../../SurfaceMetaContext';
import { apiClient } from '../../../../api';
import { failedBody, previewBody, unsupportedBody } from '../../../../utils/agentCardTestFixtures';

jest.mock('../../../../api', () => ({ apiClient: { fetch: jest.fn() } }));

const mockFetch = apiClient.fetch as jest.Mock;
const reply = (status: number, body: unknown = {}) => ({
  ok: status >= 200 && status < 300,
  status,
  json: async () => body,
});

const renderLine = (meta: Partial<SurfaceMetaValue> = {}) => {
  const onOpenAgentCard = jest.fn();
  render(
    <SurfaceMetaProvider
      value={
        {
          isCreate: false,
          surfaceId: 's-123',
          onOpenAgentCard,
          ...meta,
        } as SurfaceMetaValue
      }
    >
      <AgentCardFetchLine />
    </SurfaceMetaProvider>
  );
  return { onOpenAgentCard };
};

const status = () => screen.getByTestId('managed-agent-card-fetch-status');

beforeEach(() => jest.resetAllMocks());

describe('AgentCardFetchLine', () => {
  it('says the card fetch is OK and opens the tab from the link', async () => {
    mockFetch.mockResolvedValue(reply(200, previewBody()));
    const { onOpenAgentCard } = renderLine();
    await waitFor(() => expect(status()).toHaveTextContent('Card fetch: OK'));
    expect(status()).toHaveClass('agent-card-fetch-ok');
    expect(status()).not.toHaveClass('text-success');
    expect(screen.getByTestId('managed-agent-card-fetch-icon')).toHaveClass('fa-check');
    const link = screen.getByRole('button', { name: 'View agent cards' });
    expect(link).toBe(screen.getByTestId('managed-agent-card-fetch-link'));
    fireEvent.click(link);
    expect(onOpenAgentCard).toHaveBeenCalledTimes(1);
  });

  it('says the card fetch is failing with the cause and the HTTP status', async () => {
    mockFetch.mockResolvedValue(reply(200, failedBody('needs_token', 401)));
    renderLine();
    await waitFor(() =>
      expect(status()).toHaveTextContent('Card fetch: failing (Needs a token — HTTP 401)')
    );
    expect(status()).toHaveClass('agent-card-fetch-failing');
    expect(status()).not.toHaveClass('text-danger');
    expect(screen.getByTestId('managed-agent-card-fetch-icon')).toHaveClass(
      'fa-triangle-exclamation'
    );
  });

  it('leaves out the HTTP status when the gateway did not reach the agent', async () => {
    mockFetch.mockResolvedValue(reply(200, failedBody('timeout', null)));
    renderLine();
    await waitFor(() => expect(status()).toHaveTextContent('Card fetch: failing (Timed out)'));
    expect(status()).not.toHaveTextContent('HTTP');
  });

  it('says the gateway generates the card for an A2A proxy', async () => {
    mockFetch.mockResolvedValue(reply(200, previewBody({ generated: true, before: null })));
    renderLine();
    await waitFor(() => expect(status()).toHaveTextContent('Card: generated by the gateway'));
    expect(status()).toHaveClass('text-muted');
  });

  it('shows a checking status first, and an unavailable status when the read fails', async () => {
    mockFetch.mockResolvedValue(reply(500));
    renderLine();
    expect(status()).toHaveTextContent('Card fetch: checking…');
    await waitFor(() => expect(status()).toHaveTextContent('Card fetch: status unavailable'));
  });

  it('renders nothing for a surface the gateway does not run or that has no card', async () => {
    mockFetch.mockResolvedValue(reply(200, unsupportedBody('not_running')));
    renderLine();
    await waitFor(() => expect(mockFetch).toHaveBeenCalled());
    await waitFor(() =>
      expect(screen.queryByTestId('managed-agent-card-fetch')).not.toBeInTheDocument()
    );
  });

  it('renders nothing and fetches nothing for an unsaved surface or without the tab', () => {
    renderLine({ isCreate: true, surfaceId: undefined });
    renderLine({ onOpenAgentCard: undefined });
    expect(screen.queryByTestId('managed-agent-card-fetch')).not.toBeInTheDocument();
    expect(mockFetch).not.toHaveBeenCalled();
  });

  it('renders nothing outside a surface editor', () => {
    render(<AgentCardFetchLine />);
    expect(screen.queryByTestId('managed-agent-card-fetch')).not.toBeInTheDocument();
    expect(mockFetch).not.toHaveBeenCalled();
  });

  it('reads the card again when the saved surface changes or a Refresh succeeds', async () => {
    mockFetch.mockResolvedValue(reply(200, previewBody()));
    const value = { isCreate: false, surfaceId: 's-123', onOpenAgentCard: jest.fn() };
    const view = render(
      <SurfaceMetaProvider
        value={{ ...value, agentCardFetchRevision: [0, 0] } as unknown as SurfaceMetaValue}
      >
        <AgentCardFetchLine />
      </SurfaceMetaProvider>
    );
    await waitFor(() => expect(mockFetch).toHaveBeenCalledTimes(1));
    view.rerender(
      <SurfaceMetaProvider
        value={{ ...value, agentCardFetchRevision: [0, 1] } as unknown as SurfaceMetaValue}
      >
        <AgentCardFetchLine />
      </SurfaceMetaProvider>
    );
    await waitFor(() => expect(mockFetch).toHaveBeenCalledTimes(2));
  });
});
