import React from 'react';
import {
  useAgentCardPreview,
  type AgentCardPreviewState,
} from '../../../hooks/useAgentCardPreview';
import { describeFetchFailure } from '../../../utils/agentCardPreview';
import { useOptionalSurfaceMeta } from '../SurfaceMetaContext';

type Tone = 'muted' | 'success' | 'danger';

const TONE_CLASS: Record<Tone, string> = {
  muted: 'text-muted',
  success: 'agent-card-fetch-ok',
  danger: 'agent-card-fetch-failing',
};

const TONE_ICON: Record<Tone, string> = {
  muted: 'fa-circle-info',
  success: 'fa-check',
  danger: 'fa-triangle-exclamation',
};

function fetchLine(state: AgentCardPreviewState): { text: string; tone: Tone } | null {
  if (state.status === 'unavailable') {
    return { text: 'Card fetch: status unavailable', tone: 'muted' };
  }
  if (state.status !== 'ready') return { text: 'Card fetch: checking…', tone: 'muted' };
  const { preview } = state;
  if (!preview.supported) return null;
  if (preview.generated) return { text: 'Card: generated by the gateway', tone: 'muted' };
  if (preview.fetch.status === 'ok') return { text: 'Card fetch: OK', tone: 'success' };
  const failure = describeFetchFailure(preview.fetch);
  return {
    text: failure ? `Card fetch: failing (${failure})` : 'Card fetch: failing',
    tone: 'danger',
  };
}

const AgentCardFetchLine: React.FC = () => {
  const meta = useOptionalSurfaceMeta();
  const onOpen = meta?.onOpenAgentCard;
  const surfaceId = !meta?.isCreate && onOpen ? meta?.surfaceId : undefined;
  const { state } = useAgentCardPreview(surfaceId, meta?.agentCardFetchRevision);

  if (!surfaceId || !onOpen) return null;
  const line = fetchLine(state);
  if (!line) return null;

  return (
    <div className="config-section agent-card-fetch-line" data-testid="managed-agent-card-fetch">
      <span
        className={TONE_CLASS[line.tone]}
        aria-live="polite"
        data-testid="managed-agent-card-fetch-status"
      >
        <i
          className={`fas ${TONE_ICON[line.tone]} me-1`}
          aria-hidden="true"
          data-testid="managed-agent-card-fetch-icon"
        />
        {line.text}
      </span>
      <button
        type="button"
        className="btn btn-link btn-sm p-0 ms-2 align-baseline"
        onClick={onOpen}
        data-testid="managed-agent-card-fetch-link"
      >
        View agent cards
      </button>
    </div>
  );
};

export default AgentCardFetchLine;
